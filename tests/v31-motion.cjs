const { chromium } = require('playwright');
const { existsSync, mkdirSync } = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const executable = ['/usr/bin/google-chrome','/opt/google/chrome/chrome','/usr/bin/chromium'].find(existsSync);
  assert(executable, 'Chrome/Chromium must be available on the CI runner');
  const browser = await chromium.launch({headless:true,executablePath:executable,args:['--no-sandbox']});
  const source = 'file://' + path.resolve('index.html');
  mkdirSync('test-results', {recursive:true});
  for (const [name,width,height] of [['desktop',1440,900],['tablet',834,1112],['mobile',390,844],['narrow',320,720]]) {
    const page = await browser.newPage({viewport:{width,height},reducedMotion:'no-preference'});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(source);
    await page.locator('#motionToggle').waitFor();
    await page.locator('#overview .studio-motion-art').waitFor();
    assert.equal(await page.locator('#motionToggle').getAttribute('aria-pressed'),'true');
    assert.equal(await page.locator('html').evaluate(x=>x.classList.contains('motion-paused')),false);
    const art = await page.locator('.studio-motion-art').evaluate(el=>getComputedStyle(el).display);
    if(width >= 1190) assert.notEqual(art,'none','hero motion art should appear on wide desktop');
    const overflow = await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
    assert(overflow <= 3,name+' has horizontal overflow: '+overflow);
    await page.screenshot({path:'test-results/v31-'+name+'-overview.png'});
    await page.locator('#motionToggle').click();
    assert.equal(await page.locator('#motionToggle').getAttribute('aria-pressed'),'false');
    assert(await page.locator('html').evaluate(x=>x.classList.contains('motion-paused')),'pause class missing');
    await page.locator('#motionToggle').click();
    assert.equal(await page.locator('#motionToggle').getAttribute('aria-pressed'),'true');
    if (width <= 1020) await page.locator('#menubtn').click();
    await page.locator('#nav [data-open="content"]').click();
    await page.locator('.ticket-thumb .studio-preview-mark').first().waitFor();
    assert(await page.locator('.ticket-thumb .studio-preview-mark').count() > 0,'creative thumbnails not decorated');
    await page.screenshot({path:'test-results/v31-'+name+'-content.png'});
    if (width <= 1020) await page.locator('#menubtn').click();
    await page.locator('#nav [data-open="performance"]').click();
    assert(await page.locator('#performance .panel').count() > 0);
    if (width <= 1020) await page.locator('#menubtn').click();
    await page.locator('#nav [data-open="calendar"]').click();
    await page.locator('[data-cal-tab="workload"]').click();
    await page.locator('.personcard').first().click();
    const dlg = page.locator('#overlay.open [role="dialog"]');
    const r = await dlg.boundingBox();
    assert(r && Math.abs(r.x+r.width/2-width/2)<4 && Math.abs(r.y+r.height/2-height/2)<4,name+' centered modal position regression');
    await page.locator('#closedrawer').click();
    const finalOverflow = await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
    assert(finalOverflow <= 3,name+' has horizontal overflow after navigating: '+finalOverflow);
    assert.deepEqual(errors,[],name+' runtime JS errors');
    await page.close();
    console.log('PASS '+name+' motion, UI navigation, creative previews and centered modal');
  }
  const reduced = await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
  await reduced.goto(source);
  await reduced.locator('#motionToggle').waitFor();
  await reduced.locator('#overview .studio-motion-art').waitFor();
  assert.equal(await reduced.locator('#motionToggle').getAttribute('aria-pressed'),'false');
  assert(await reduced.locator('#motionToggle').isDisabled(),'reduced motion button should indicate OS preference');
  assert(await reduced.locator('html').evaluate(x=>x.classList.contains('motion-paused')));
  const animated = await reduced.locator('.studio-halo').evaluate(el=>getComputedStyle(el).animationName);
  assert.equal(animated,'none','OS reduced motion must disable orbit');
  await reduced.close();
  await browser.close();
  console.log('PASS V3.1 motion on/off, reduced-motion accessibility and responsive browser regressions');
})().catch(e=>{console.error(e);process.exit(1)});